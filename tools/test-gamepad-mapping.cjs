'use strict';
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const ts = require('C:/Program Files/Huawei/DevEco Studio/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'entry/src/main/ets/model/GamepadMapping.ets'), 'utf8');
const context = { exports: {}, Math, Number, JSON, Map, Array, Object };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText, context);
const { GamepadMapper, defaultGamepadMapping, validGamepadMappingValue, decodeGamepadMapping, gamepadMappingHasConflicts } = context.exports;
const config = defaultGamepadMapping();
assert(validGamepadMappingValue(JSON.stringify(config)));
assert(!validGamepadMappingValue('{"version":1,"bindings":[]}'));
assert(!validGamepadMappingValue(JSON.stringify({ ...config, deadzone: 0 })));
const legacy = JSON.parse(JSON.stringify(config));
legacy.bindings = legacy.bindings.filter(binding => binding.code !== 2313);
assert(validGamepadMappingValue(JSON.stringify(legacy)), 'pre-Home mappings remain valid');
assert.equal(decodeGamepadMapping(JSON.stringify(legacy)).bindings.find(binding => binding.code === 2313).target, 'none');
assert.equal(decodeGamepadMapping(JSON.stringify(legacy)).bindings.find(binding => binding.code === 2301).target, 'k:44');
assert.equal(decodeGamepadMapping('corrupt').bindings.length, config.bindings.length);
assert.equal(gamepadMappingHasConflicts(config), false);
const duplicate = JSON.parse(JSON.stringify(config));
duplicate.bindings[1].target = duplicate.bindings[0].target;
assert(gamepadMappingHasConflicts(duplicate));
const bothSticks = JSON.parse(JSON.stringify(config));
bothSticks.leftStick = 'arrows'; bothSticks.rightStick = 'arrows';
bothSticks.bindings.forEach(binding => { binding.target = 'none'; });
assert(gamepadMappingHasConflicts(bothSticks), 'two sticks assigned to the same arrows conflict');
const events = [], moves = [];
const mapper = new GamepadMapper((target, down) => events.push([target, down]), (x, y) => moves.push([x, y]));
mapper.button(1, 2301, true);
mapper.button(1, 2301, true); // repeat does not repeat an edge
mapper.button(-1, 2301, true); // same target from virtual source
mapper.button(1, 2301, false);
assert.deepEqual(events, [['k:44', true]]);
mapper.button(-1, 2301, false);
assert.deepEqual(events, [['k:44', true], ['k:44', false]]);
events.length = 0;
mapper.axis(1, 1, 0.1, 0.1); // radial deadzone
assert.equal(events.length, 0);
mapper.axis(1, 1, 0.8, -0.8);
assert.deepEqual(events, [['k:7', true], ['k:26', true]]);
mapper.axis(1, 1, 0, 0);
assert.deepEqual(events.slice(-2), [['k:7', false], ['k:26', false]]);
events.length = 0;
mapper.button(2, 2310, true);
mapper.axis(2, 4, 0.8, 0);
mapper.button(2, 2310, false);
assert.deepEqual(events, [['mouse:left', true]], 'axis and button sources share the output');
mapper.axis(2, 4, 0, 0);
assert.deepEqual(events, [['mouse:left', true], ['mouse:left', false]]);
events.length = 0;
mapper.axis(1, 0, -1, 0);
mapper.button(2, 2302, true);
mapper.releaseDevice(1);
assert.deepEqual(events, [['k:80', true], ['k:6', true], ['k:80', false]]);
mapper.releaseAll();
assert.deepEqual(events.slice(-1), [['k:6', false]]);
mapper.axis(-1, 2, 0.8, 0);
mapper.tick(1000); mapper.tick(1016);
assert(moves.length >= 2 && moves.every(([x, y]) => x > 0 && y === 0));
mapper.releaseDevice(-1);
const before = moves.length; mapper.tick(1032);
assert.equal(moves.length, before);
events.length = 0;
mapper.button(1, 2301, true);
mapper.setMapping(duplicate); // remapping releases old held outputs first
assert.deepEqual(events, [['k:44', true], ['k:44', false]]);
events.length = 0;
mapper.setMapping(config);
mapper.screenButton(1, 'k:44', true);
mapper.button(1, 2301, true);
mapper.screenButton(1, 'k:44', false);
assert.deepEqual(events, [['k:44', true]], 'screen and controller share output ownership');
mapper.releaseAll();
assert.deepEqual(events, [['k:44', true], ['k:44', false]], 'disconnect releases shared output');
events.length = 0;
mapper.screenButton(1, 'invalid', true);
assert.equal(events.length, 0, 'invalid screen targets cannot generate input');
console.log('PASS gamepad mappings, validation, simultaneous sources, deadzones, hysteresis and release safety');
