'use strict';
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const ts = require('C:/Program Files/Huawei/DevEco Studio/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript');
const source = fs.readFileSync('entry/src/main/ets/model/SecondaryTouchGesture.ets', 'utf8');
const context = { exports: {}, Math }; vm.runInNewContext(ts.transpile(source), context);
const Gesture = context.exports.SecondaryTouchGesture;
const p = (id, x, y) => ({id,x,y}); const kinds = a => Array.from(a, v => v.kind);
let g = new Gesture();
assert.deepEqual(kinds(g.handle('down', [p(1,10,10)], [p(1,10,10)], 0)), ['preview']);
assert.deepEqual(kinds(g.handle('up', [], [p(1,10,10)], 100)), ['click']);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0);
assert.deepEqual(kinds(g.handle('move',[p(1,30,10)],[],20)), ['down','move']);
assert.deepEqual(kinds(g.handle('up',[],[p(1,30,10)],40)), ['up']);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0);
assert.deepEqual(kinds(g.longPress()), ['right']);
assert.deepEqual(kinds(g.handle('up',[],[p(1,10,10)],700)), []);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0); g.handle('down',[p(1,10,10),p(2,30,10)],[],20);
assert.deepEqual(kinds(g.handle('up',[p(2,30,10)],[p(1,10,10)],100)), ['right']);
assert.deepEqual(kinds(g.handle('up',[],[p(2,30,10)],110)), []);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0); g.handle('down',[p(1,10,10),p(2,30,10)],[],20);
assert.deepEqual(kinds(g.handle('move',[p(1,10,30),p(2,30,30)],[],40)), ['scroll']);
assert.deepEqual(kinds(g.handle('up',[p(2,30,30)],[p(1,10,30)],100)), []);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0); g.handle('down',[p(1,10,10),p(2,30,10)],[],20);
const zoom = g.handle('move',[p(1,0,10),p(2,40,10)],[],40);
assert.deepEqual(kinds(zoom), ['zoom']); assert.equal(zoom[0].scale,2);
assert.deepEqual(kinds(g.handle('up',[p(2,40,10)],[p(1,0,10)],100)), []);
g = new Gesture(); g.handle('down',[p(1,10,10)],[],0); g.handle('move',[p(1,30,10)],[],10);
assert.deepEqual(kinds(g.handle('down',[p(1,30,10),p(2,40,10)],[],20)), ['release']);
assert.deepEqual(kinds(g.handle('cancel',[],[],30)), []);
console.log('PASS secondary touch: click, drag, long press, two-finger tap, scroll, pinch and cancellation');
