'use strict';
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const root = path.join(__dirname, '..');
const base = path.join(root, 'build-artifacts/i18n-tooling');
let opencc;
try { opencc = require(path.join(base, 'node_modules/opencc-js')); }
catch (_) { throw Error('Install build-only conversion tool: npm install --prefix build-artifacts/i18n-tooling --no-audit --no-fund opencc-js@1.4.2'); }
const traditional = opencc.Converter({ from: 'cn', to: 'tw' });
// Checked-in upstream subset + hashes, so catalog generation never changes with
// a network fetch of RustDesk master. No translation library ships in the app.
const common = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n-common.json'), 'utf8'));
const officialEn = { ...common.english }, officialTw = common.traditional;
const custom = {};
for (const line of fs.readFileSync(path.join(__dirname, 'i18n-en.tsv'), 'utf8').split(/\r?\n/)) {
  if (!line || line.startsWith('#')) continue;
  const tab = line.indexOf('\t');
  if (tab < 0) throw Error('Missing TAB: ' + line);
  const key = line.slice(0, tab).replace(/\\n/g, '\n');
  const value = line.slice(tab + 1).replace(/\\n/g, '\n');
  if (custom[key] !== undefined) throw Error('Duplicate: ' + key);
  custom[key] = value;
}
const inventory = JSON.parse(cp.execFileSync(process.execPath, [path.join(__dirname, 'localize-ui.cjs'), '--inventory'], { encoding: 'utf8' }));
const aliasSource = fs.readFileSync(path.join(root, 'entry/src/main/ets/utils/I18n.ets'), 'utf8');
for (const m of aliasSource.matchAll(/'([^']+)': '([^']+)'/g)) {
  inventory.keys.push(m[2]);
  if (!officialEn[m[2]]) officialEn[m[2]] = m[1];
}
const native = fs.readFileSync(path.join(root, 'entry/src/main/cpp/napi_init.cpp'), 'utf8');
for (const m of native.matchAll(/return "([^"\n]*[\u4e00-\u9fff][^"\n]*)"/g)) inventory.keys.push(m[1]);
inventory.keys.push('远端登录失败，请检查远端设备并导出诊断日志');
const keys = [...new Set([...inventory.keys, ...Object.keys(custom)])];
for (const key of keys) {
  if (!custom[key] && key.includes('\n')) {
    const lines = key.split('\n').map(line => custom[line] || officialEn[line]);
    if (lines.every(Boolean)) custom[key] = lines.join('\n');
  }
}
const missing = keys.filter(key => !custom[key] && !officialEn[key]);
if (process.argv.includes('--missing')) { console.log(missing.join('\n')); process.exit(0); }
if (missing.length) { console.error('Missing translations:', missing.length, missing.slice(0, 15)); process.exit(1); }
const english = {}, taiwan = {};
for (const key of keys) {
  english[key] = custom[key] || officialEn[key];
  taiwan[key] = officialTw[key] || traditional(key);
}
const emit = object => JSON.stringify(object, null, 2);
const source = '// Generated by tools/build-i18n-catalog.cjs.\n' +
  '// Common translations adapted from RustDesk src/lang (AGPL-3.0); custom text: tools/i18n-en.tsv.\n' +
  `export const ENGLISH: Record<string, string> = ${emit(english)}\n\n` +
  `export const TRADITIONAL: Record<string, string> = ${emit(taiwan)}\n\n` +
  `export const DYNAMIC_KEYS: string[] = ${emit([...new Set([...inventory.templates, '连接失败（错误码：{0}）'])])}\n`;
fs.writeFileSync(path.join(root, 'entry/src/main/ets/utils/I18nCatalog.ets'), source);
console.log('Generated', keys.length, 'translations and', inventory.templates.length, 'dynamic templates');

// System-owned permission prompts are resource based, not ArkUI display text.
const resourceFile = path.join(root, 'entry/src/main/resources/base/element/string.json');
const resources = JSON.parse(fs.readFileSync(resourceFile, 'utf8'));
const resourceChinese = {
  permission_voice_call_reason: '用于您主动发起并经远端接听的语音通话；通话期间可在后台继续采集，挂断或后台任务被系统停止后结束采集',
  module_desc: '芝麻远控 - 远程桌面客户端', EntryAbility_desc: '远程桌面应用',
  permission_microphone_reason: '用于您主动发起并经远端接听的语音通话',
  permission_background_remote_session_reason: '用于息屏或切到后台时保持正在进行的远程桌面连接'
};
const resourceEnglish = {
  permission_voice_call_reason: 'Used for voice calls you initiate and the remote user accepts. Capture may continue in the background during the call, and stops when you hang up or the system stops the background task.',
  permission_microphone_reason: 'Used for voice calls you initiate and the remote user accepts.'
};
const aliases = Object.fromEntries([...aliasSource.matchAll(/'([^']+)': '([^']+)'/g)].map(m => [m[1], m[2]]));
for (const folder of ['base', 'en', 'zh_CN', 'zh_Hant']) {
  const output = { string: resources.string.map(item => {
    const englishValue = resourceEnglish[item.name] || item.value;
    const chineseValue = resourceChinese[item.name] || aliases[item.value] || item.value;
    return { name: item.name, value: folder === 'zh_CN' ? chineseValue :
      folder === 'zh_Hant' ? traditional(chineseValue) : englishValue };
  }) };
  const target = path.join(root, 'entry/src/main/resources', folder, 'element');
  fs.mkdirSync(target, { recursive: true });
  fs.writeFileSync(path.join(target, 'string.json'), emit(output) + '\n');
}

// Launcher/system app labels follow the same approved localized brand as the
// ability label, without changing the bundle name or resource identifiers.
for (const folder of ['base', 'en', 'zh_CN', 'zh_Hant']) {
  const target = path.join(root, 'AppScope/resources', folder, 'element');
  fs.mkdirSync(target, { recursive: true });
  const name = folder === 'zh_Hant' ? '芝麻遠控' : '芝麻远控';
  fs.writeFileSync(path.join(target, 'string.json'), emit({ string: [{ name: 'app_name', value: name }] }) + '\n');
}
