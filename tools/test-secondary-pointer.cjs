'use strict';
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const ts = require('C:/Program Files/Huawei/DevEco Studio/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript');
const src = fs.readFileSync(path.resolve(__dirname, '../entry/src/main/ets/model/SecondaryPointerPolicy.ets'), 'utf8');
const context = { exports: {}, Number, Math }; vm.runInNewContext(ts.transpile(src), context);
const point = context.exports.secondaryRemotePoint;
assert.equal(point(5, 10, 1000, 1000, 1920, 1080, false), undefined, 'letterbox must not inject');
const center = point(500, 500, 1000, 1000, 1920, 1080, false);
assert.equal(center.x, 960); assert.equal(center.y, 540);
const drag = point(1200, -20, 1000, 1000, 1920, 1080, true);
assert.equal(drag.x, 1919); assert.equal(drag.y, 0);
assert.equal(point(NaN, 10, 1000, 1000, 1920, 1080, false), undefined);
assert.equal(point(10, 10, 0, 1000, 1920, 1080, false), undefined);
const zoomCenter = point(500, 500, 1000, 1000, 1920, 1080, false, 2, 0, 0);
assert.equal(zoomCenter.x, 960); assert.equal(zoomCenter.y, 540);
const panned = point(500, 500, 1000, 1000, 1920, 1080, false, 2, 100, 0);
assert.equal(panned.x, 864); assert.equal(panned.y, 540);
assert.equal(point(10, 10, 1000, 1000, 1920, 1080, false, 0), undefined);
console.log('PASS secondary pointer: letterbox rejection, aspect ratio, drag clipping and invalid values');
