int decoder_submit(PDECODE_UNIT unit)
{
    Client *c = gClient.load();
    if (!c || !unit || !c->codec || c->stopping || c->failed) return DR_NEED_IDR;
    uint32_t number = static_cast<uint32_t>(unit->frameNumber);
    const uint32_t diff = number - c->lastSequence;
    uint32_t lost = c->sawFrame && diff > 1 && diff < 100000 ? diff - 1 : 0;
#ifdef SESAME_CORE_RX_WITNESS
    if(lost && c->lanRxWatch) sr_gap(c->lastSequence+1,lost);
#endif
    const uint64_t now = LiGetMillis();
    c->waitSince=0;c->waitUnits=0;
    const uint64_t gap = c->lastUnitAt && now >= c->lastUnitAt ? now - c->lastUnitAt : 0;
    const uint32_t hostDms = unit->frameHostProcessingLatency;
    if (hostDms) {
        c->hostProcessSumDms += hostDms;
        c->hostProcessSamples++;
        if (hostDms > c->hostProcessPeakDms.load()) c->hostProcessPeakDms.store(hostDms);
    }
    if (lost || gap >= 140 || hostDms >= 750) {
        const uint64_t assembly = unit->enqueueTimeMs >= unit->receiveTimeMs ?
            unit->enqueueTimeMs - unit->receiveTimeMs : 0;
        const uint64_t wait = now >= unit->enqueueTimeMs ? now - unit->enqueueTimeMs : 0;
        OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
            "unit_gap at=%{public}llu previous_frame=%{public}u frame=%{public}u missing=%{public}u "
            "gap=%{public}llu assembly=%{public}llu callback_wait=%{public}llu idr=%{public}d host_01ms=%{public}u",
            static_cast<unsigned long long>(now), c->lastSequence, number, lost,
            static_cast<unsigned long long>(gap), static_cast<unsigned long long>(assembly),
            static_cast<unsigned long long>(wait), unit->frameType == FRAME_TYPE_IDR ? 1 : 0, hostDms);
    }
    c->gaps += lost;
    c->lastUnitAt = now;
    c->lastSequence = number;
    c->sawFrame = true;
    c->received++;
    using FreshAction = FreshFrameRecovery::Action;
    FreshFrameRecovery::Result fresh{FreshAction::Pass,0};
    if (c->freshRecovery) {
        fresh=c->freshFrame.observe(now,unit->presentationTimeMs,hostDms!=0,
            unit->frameType==FRAME_TYPE_IDR,gap,c->rendered.load()!=0);
        if (fresh.action==FreshAction::Refresh) {
            c->waitingFresh=true;
            c->needIdr++;
            OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
                "freshness_request at=%{public}llu frame=%{public}u gap_ms=%{public}llu "
                "extra_ms=%{public}llu request=%{public}u",
                static_cast<unsigned long long>(now),number,static_cast<unsigned long long>(gap),
                static_cast<unsigned long long>(fresh.extraMs),c->freshFrame.requests);
            return DR_NEED_IDR;
        }
        if (fresh.action==FreshAction::Discard) {
            // In this pinned core LiCompleteVideoFrame releases any
            // other status without marking an IDR decoded or requesting
            // another one. Keep the current picture while waiting.
            return 1;
        }
    }
    if (unit->fullLength <= 0 || unit->fullLength > 2 * 1024 * 1024) {
        keyDecoderReject(*c,number,unit->frameType==FRAME_TYPE_IDR,2);
        c->needIdr++;
        return DR_NEED_IDR;
    }
    Slot slot{};
#ifdef SESAME_KEY_SLOT_TRIAL
    bool waitedForSlot=false;
    uint64_t actualWaitUs=0;
    auto recordWait=[&](bool pushed){
        if(!waitedForSlot) return;
        // No log I/O in the serial submit callback before returning DR_NEED_IDR.
        c->slotBridge.finish(number,actualWaitUs,pushed,unit->frameType==FRAME_TYPE_IDR);
    };
#endif
    {
#ifdef SESAME_KEY_SLOT_TRIAL
        std::unique_lock<std::mutex> lock(c->mutex);
        if(!c->count && c->keyRecoveryTrial && c->rendered.load()) {
            const auto start=Clock::now();
            const auto us=std::chrono::duration_cast<std::chrono::microseconds>(start.time_since_epoch()).count();
            if(c->slotBridge.begin(us,!c->stopping && !c->failed && !media_cancelled && requested_display.load()<0)) {
                c->waitingSlot=true;waitedForSlot=true;
                c->slotReady.wait_until(lock,start+std::chrono::microseconds(LanSlotBridge::deadlineUs),[&] {
                    return c->count || c->stopping || c->failed || media_cancelled || requested_display.load()>=0;
                });
                c->waitingSlot=false;
                actualWaitUs=std::chrono::duration_cast<std::chrono::microseconds>(Clock::now()-start).count();
                if(c->stopping || c->failed || media_cancelled || requested_display.load()>=0) {
                    lock.unlock();recordWait(false);return DR_NEED_IDR;
                }
            }
        }
#else
        std::lock_guard<std::mutex> lock(c->mutex);
#endif
        if (c->count == 0) {
#ifdef SESAME_KEY_SLOT_TRIAL
            if(c->keyRecoveryTrial && c->rendered.load() && !c->stopping && !c->failed && !media_cancelled && requested_display.load()<0)
                c->slotReturns.reject(number,std::chrono::duration_cast<std::chrono::microseconds>(Clock::now().time_since_epoch()).count());
            lock.unlock();recordWait(false);
#endif
            keyDecoderReject(*c,number,unit->frameType==FRAME_TYPE_IDR,1);
            c->needIdr++;
            return DR_NEED_IDR;
        }
        slot = c->slots[--c->count];
    }
    int cap = OH_AVBuffer_GetCapacity(slot.buffer);
    auto *dst = OH_AVBuffer_GetAddr(slot.buffer);
    int written = 0;
    bool usable = dst && cap >= unit->fullLength;
    if (usable) {
        for (auto *seg = unit->bufferList; seg; seg = seg->next) {
            if (!seg->data || seg->length <= 0 || seg->length > unit->fullLength - written) {
                usable = false;
                break;
            }
            std::memcpy(dst + written, seg->data, seg->length);
            written += seg->length;
        }
        usable = usable && written == unit->fullLength;
    }
    if (!usable) {
#ifdef SESAME_KEY_SLOT_TRIAL
        recordWait(false);
#endif
        keyDecoderReject(*c,number,unit->frameType==FRAME_TYPE_IDR,3);
        c->needIdr++;
        std::lock_guard<std::mutex> lock(c->mutex);
        if (c->count < c->slots.size()) c->slots[c->count++] = slot;
        return DR_NEED_IDR;
    }
    OH_AVCodecBufferAttr attr{
        static_cast<int64_t>(unit->presentationTimeMs) * 1000,
        written, 0,
        unit->frameType == FRAME_TYPE_IDR ? AVCODEC_BUFFER_FLAGS_SYNC_FRAME : 0U
    };
    if (fresh.action==FreshAction::Resume) {
        c->freshWaitStarted=c->freshFrame.began;
        c->freshPicturePts=static_cast<uint64_t>(attr.pts)+1;
    }
#ifdef SESAME_PHONE_RX_TRIAL
    if (c->lanRxWatch && (lost || c->lanPending.load())) {
        std::lock_guard<std::mutex> lk(c->lanWitnessLock);
        if(lost && !c->lanPending.load()) {c->lanWitness.observedAtDecoder(now,number);c->lanPending=true;}
        c->lanWitness.submitting(now,number,static_cast<uint64_t>(attr.pts),unit->frameType==FRAME_TYPE_IDR);
    }
#endif
    if (OH_AVBuffer_SetBufferAttr(slot.buffer, &attr) != 0 ||
        OH_VideoDecoder_PushInputBuffer(c->codec, slot.index) != 0) {
#ifdef SESAME_KEY_SLOT_TRIAL
        recordWait(false);
#endif
        keyDecoderReject(*c,number,unit->frameType==FRAME_TYPE_IDR,4);
        c->failed = true;
        c->needIdr++;
        return DR_NEED_IDR;
    }
    c->submitted++;
#ifdef SESAME_KEY_SLOT_TRIAL
    recordWait(true);
#endif
    c->bytes += written;
    if (fresh.action==FreshAction::Resume) {
        c->freshFrame.submittedFresh();
        c->waitingFresh=false;
        OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
            "freshness_submit at=%{public}llu frame=%{public}u skipped=%{public}u "
            "extra_ms=%{public}llu wait_ms=%{public}llu requests=%{public}u",
            static_cast<unsigned long long>(now),number,c->freshFrame.dropped,
            static_cast<unsigned long long>(fresh.extraMs),static_cast<unsigned long long>(now-c->freshFrame.began),
            c->freshFrame.requests);
    }
    return DR_OK;
}

