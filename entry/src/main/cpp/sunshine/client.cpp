std::atomic<Client *> gClient{nullptr};

void keyDecoderReject(Client &c,uint32_t frame,bool key,unsigned why) {
#ifdef SESAME_PHONE_RX_TRIAL
    if (!c.lanRxWatch || !c.rendered.load()) return;
    const uint64_t now=LiGetMillis();
    {
        std::lock_guard<std::mutex> lk(c.lanWitnessLock);
        c.lanWitness.rejectedAtDecoder(now,frame);c.lanPending=true;
    }
    if(c.needIdr.load()<512) OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,
        "lan_key_reject f=%{public}u why=%{public}u at=%{public}llu idr=%{public}u",
        frame,why,(unsigned long long)now,unsigned(key));
#else
    (void)c;(void)frame;(void)key;(void)why;
#endif
}

void codec_error(OH_AVCodec *, int32_t code, void *userdata)
{
    auto &c = *static_cast<Client *>(userdata);
    c.failed = true;
#ifdef SESAME_KEY_SLOT_TRIAL
    c.slotReady.notify_one();
#endif
    OH_LOG_Print(LOG_APP, LOG_WARN, kLog, kTag, "decoder_error=%{public}d", code);
}
void codec_format(OH_AVCodec *, OH_AVFormat *format, void *userdata)
{
#ifdef SESAME_SUNSHINE_LONG_BENCH
    int32_t w=0,h=0;
    auto &c=*static_cast<Client *>(userdata);
    const bool valid=format && OH_AVFormat_GetIntValue(format,OH_MD_KEY_VIDEO_PIC_WIDTH,&w) &&
        OH_AVFormat_GetIntValue(format,OH_MD_KEY_VIDEO_PIC_HEIGHT,&h) && w>0 && h>0 && w<=8192 && h<=8192;
    c.outputPicture.store(valid ? (uint64_t(w)<<32)|uint32_t(h) : 0);
#endif
}
void codec_input(OH_AVCodec *, uint32_t index, OH_AVBuffer *buffer, void *userdata)
{
    auto &c = *static_cast<Client *>(userdata);
    if (!buffer || c.stopping) return;
#ifdef SESAME_KEY_SLOT_TRIAL
    bool wake=false;
#endif
    {
        std::lock_guard<std::mutex> lock(c.mutex);
        if (c.count < c.slots.size()) {
            c.slots[c.count++] = {index, buffer};
#ifdef SESAME_KEY_SLOT_TRIAL
            if (!c.stopping && !c.failed && c.slotReturns.pending!=c.slotReturns.used)
                c.slotReturns.available(std::chrono::duration_cast<std::chrono::microseconds>(Clock::now().time_since_epoch()).count());
#endif
        } else c.failed = true;
#ifdef SESAME_KEY_SLOT_TRIAL
        wake=c.waitingSlot;
#endif
    }
#ifdef SESAME_KEY_SLOT_TRIAL
    if(wake) c.slotReady.notify_one(); // publish the slot before waking the consumer
#endif
}
void codec_output(OH_AVCodec *codec, uint32_t index, OH_AVBuffer *buffer, void *userdata)
{
    auto &c = *static_cast<Client *>(userdata);
    if (c.stopping) {
        OH_VideoDecoder_FreeOutputBuffer(codec, index);
        return;
    }
    const auto outStart = Clock::now();
    auto expectedPts = c.freshPicturePts.load();
    bool returnedFreshPicture = false;
    if (expectedPts && buffer) {
        OH_AVCodecBufferAttr attr{};
        if (OH_AVBuffer_GetBufferAttr(buffer,&attr)==0 && attr.pts>=0 &&
            static_cast<uint64_t>(attr.pts)==expectedPts-1) returnedFreshPicture=true;
    }
#ifdef SESAME_PHONE_RX_TRIAL
    OH_AVCodecBufferAttr lanAttr{};
    const bool traceLan=c.lanPending.load() && buffer && OH_AVBuffer_GetBufferAttr(buffer,&lanAttr)==0 && lanAttr.pts>=0;
#endif
    if (OH_VideoDecoder_RenderOutputBuffer(codec, index) != 0) {
        c.badRender++;
        return;
    }
#ifdef SESAME_PHONE_RX_TRIAL
    if (traceLan) {
        std::lock_guard<std::mutex> lk(c.lanWitnessLock);
        auto &w=c.lanWitness; const auto now=LiGetMillis();
        if (w.presented(now,static_cast<uint64_t>(lanAttr.pts))) {
            OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,
                "lan_key_phase f=%{public}u first=%{public}llu loss=%{public}llu wait=%{public}llu kind=%{public}u queue=%{public}llu sent=%{public}llu last=%{public}llu nq=%{public}u ns=%{public}u",
                w.unitFrame,(unsigned long long)w.first,(unsigned long long)w.firstLoss,(unsigned long long)w.firstWait,w.waitKind,
                (unsigned long long)w.queued,(unsigned long long)w.accepted,(unsigned long long)w.lastAccepted,w.queues,w.sends);
            OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,
                "lan_key_out f=%{public}u first=%{public}llu unit=%{public}llu surface=%{public}llu exact=%{public}u idr=%{public}u backup=%{public}llu tries=%{public}u",
                w.unitFrame,(unsigned long long)w.first,(unsigned long long)w.unit,(unsigned long long)now,
                unsigned(static_cast<uint64_t>(lanAttr.pts)==w.targetPts),unsigned(w.idr),(unsigned long long)w.asked,w.attempts);
            OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,"lan_loss_recovered unit_ms=%{public}llu surface_ms=%{public}llu idr=%{public}u retry=%{public}u source=%{public}u",
                (unsigned long long)(w.unit-w.first),(unsigned long long)(now-w.first),unsigned(w.idr),unsigned(w.requested),w.source);
#ifdef SESAME_KEY_RECOVERY_TRIAL
            if(c.keyRecoveryTrial) {
                const auto &s=c.shard;
                OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,
                    "lan_key_shard f=%{public}u first=%{public}llu lf=%{public}u loss=%{public}llu why=%{public}u floor=%{public}u nf=%{public}u admit=%{public}llu parity=%{public}u reloss=%{public}u",
                    w.unitFrame,(unsigned long long)w.first,s.firstLoss,(unsigned long long)s.lossAt,s.reason,s.floor,s.admitted,
                    (unsigned long long)s.admittedAt,s.parity,s.lostAgain);
                c.shard={};c.awaitShard.store(false,std::memory_order_relaxed);
            }
#endif
            w.finish();c.lanPending=false;
        }
    }
#endif
#ifdef SESAME_SUNSHINE_LONG_BENCH
    const auto pic=c.outputPicture.load();
    if (pic!=c.reportedPicture.exchange(pic) || (pic && c.rendered.load()%240==0))
        OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,"presented_picture width=%{public}u height=%{public}u",
                     static_cast<unsigned>(pic>>32),static_cast<unsigned>(pic));
#endif
    if (returnedFreshPicture && c.freshPicturePts.compare_exchange_strong(expectedPts,0)) {
        const auto at=LiGetMillis(), since=c.freshWaitStarted.load();
        OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
            "freshness_render at=%{public}llu wait_ms=%{public}llu pts_ms=%{public}llu",
            static_cast<unsigned long long>(at),
            static_cast<unsigned long long>(at>=since ? at-since : 0),
            static_cast<unsigned long long>((expectedPts-1)/1000));
    }
    auto dt = Clock::now();
    uint64_t before, backlog;
    int64_t gap = 0;
    {
        std::lock_guard<std::mutex> lock(c.mutex);
        before = c.rendered.load();
        auto presentMs=std::chrono::duration_cast<std::chrono::milliseconds>(dt.time_since_epoch()).count();
        const auto prior=lastSessionPresentMs.exchange(static_cast<uint64_t>(presentMs));
        if (!before && prior && static_cast<uint64_t>(presentMs)>=prior)
            OH_LOG_Print(LOG_APP,LOG_INFO,kLog,kTag,"render_across_restart_ms=%{public}llu",
                static_cast<unsigned long long>(static_cast<uint64_t>(presentMs)-prior));
        uint64_t inputs = c.submitted.load();
        backlog = inputs > before ? inputs - before : 0;
        if (before) {
            gap = std::chrono::duration_cast<std::chrono::milliseconds>(dt - c.renderTick).count();
            if (gap > c.maxGapMs && gap < 1000000) c.maxGapMs = static_cast<uint32_t>(gap);
            if (gap > 0 && gap < 1000000) c.renderWindowPeakMs = std::max(c.renderWindowPeakMs,static_cast<uint32_t>(gap));
        }
        c.renderTick = dt;
        c.rendered++;
    }
    if (!before && c.transition != Clock::time_point{}) {
        OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag, "switch_timing phase=first_render ms=%{public}lld",
            static_cast<long long>(std::chrono::duration_cast<std::chrono::milliseconds>(dt-c.transition).count()));
    }
    if (gap >= 140) {
        const auto callMs = std::chrono::duration_cast<std::chrono::milliseconds>(dt - outStart).count();
        OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
            "render_gap at=%{public}llu count=%{public}llu gap=%{public}lld call=%{public}lld backlog=%{public}llu",
            static_cast<unsigned long long>(LiGetMillis()), static_cast<unsigned long long>(before + 1),
            static_cast<long long>(gap), static_cast<long long>(callMs), static_cast<unsigned long long>(backlog));
    }
    ui_renders = c.rendered.load();
    if (media_phase.load() == 2) media_phase = 3;
}

int decoder_setup(int format, int w, int h, int, void *userdata, int)
{
    auto &c = *static_cast<Client *>(userdata);
    if ((EncryptionFeaturesEnabled & kEncryptedMedia) != kEncryptedMedia) {
        OH_LOG_Print(LOG_APP, LOG_WARN, kLog, kTag, "mandatory_media_encryption_missing=1");
        media_phase = 4;
        return -22;
    }
    if (format != VIDEO_FORMAT_H264 || w < 320 || h < 180 || w > 1920 || h > 1080 ||
        OH_NativeWindow_CreateNativeWindowFromSurfaceId(c.surface, &c.window) != 0 || !c.window)
        return -23;
    c.codec = OH_VideoDecoder_CreateByMime("video/avc");
    if (!c.codec) return -24;
    const OH_AVCodecCallback callbacks{codec_error, codec_format, codec_input, codec_output};
    auto *settings = OH_AVFormat_CreateVideoFormat("video/avc", w, h);
    if (!settings) return -25;
    auto rc = OH_VideoDecoder_RegisterCallback(c.codec, callbacks, &c);
    if (!rc) rc = OH_VideoDecoder_Configure(c.codec, settings);
    OH_AVFormat_Destroy(settings);
    if (!rc) rc = OH_VideoDecoder_SetSurface(c.codec, c.window);
    if (!rc) rc = OH_VideoDecoder_Prepare(c.codec);
    if (!rc) rc = OH_VideoDecoder_Start(c.codec);
    if (!rc) media_phase = 2;
    OH_LOG_Print(LOG_APP, LOG_INFO, kLog, kTag,
                 "decoder_setup_code=%{public}d enc_video=1 enc_audio=1", rc);
    return rc;
}
