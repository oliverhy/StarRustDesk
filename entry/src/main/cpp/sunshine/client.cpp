    {
        stopping = true;
        if (codec) {
            OH_VideoDecoder_Stop(codec);
            OH_VideoDecoder_Destroy(codec);
            codec = nullptr;
        }
        if (window) {
            OH_NativeWindow_DestroyNativeWindow(window);
            window = nullptr;
        }
        count = 0;
    }
    ~Client() { closeCodec(); }
